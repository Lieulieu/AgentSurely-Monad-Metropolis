/**
 * Copies contract ABIs and deployment addresses from ../contracts into
 * src/generated so the SDK and the Next.js app stay in sync.
 * Run after `hardhat compile` / deploy:  npm run sync -w @agentsurely/sdk
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(__dirname, "..", "..", "contracts");
const out = path.resolve(__dirname, "..", "src", "generated");
fs.mkdirSync(out, { recursive: true });

const artifacts: Record<string, string> = {
  surelyVaultAbi: "SurelyVault.sol/SurelyVault.json",
  mockUsdAbi: "mocks/MockUSD.sol/MockUSD.json",
  identityRegistryAbi: "mocks/MockIdentityRegistry.sol/MockIdentityRegistry.json",
  reputationRegistryAbi: "mocks/MockReputationRegistry.sol/MockReputationRegistry.json",
  validationRegistryAbi: "ValidationRegistry.sol/ValidationRegistry.json",
  subscriptionManagerAbi: "SubscriptionManager.sol/SubscriptionManager.json",
  playbookRegistryAbi: "PlaybookRegistry.sol/PlaybookRegistry.json",
  jobBoardAbi: "JobBoard.sol/JobBoard.json",
};

let abis = "// AUTO-GENERATED by scripts/sync.ts — do not edit.\n";
for (const [name, rel] of Object.entries(artifacts)) {
  const json = JSON.parse(fs.readFileSync(path.join(root, "artifacts", "contracts", rel), "utf8"));
  abis += `export const ${name} = ${JSON.stringify(json.abi, null, 2)} as const;\n\n`;
}
fs.writeFileSync(path.join(out, "abis.ts"), abis);

const depDir = path.join(root, "deployments");
const deployments: Record<number, unknown> = {};
if (fs.existsSync(depDir)) {
  for (const f of fs.readdirSync(depDir).filter((f) => f.endsWith(".json") && !f.includes(".backup"))) {
    const d = JSON.parse(fs.readFileSync(path.join(depDir, f), "utf8"));
    // upgrade-04: USDC is the money and the vault is SurelyVault. Older deployments (mUSD vault, SuretyVault)
    // are skipped so the SDK/app never mix tokens — redeploy with `npm run deploy:monad`.
    if (!d.contracts?.USDC || !d.contracts?.SurelyVault) {
      console.warn(`! ${f}: pre-upgrade-04 deployment (no USDC / SurelyVault) — skipped. Redeploy to use it.`);
      continue;
    }
    deployments[d.chainId] = { ...d.contracts, forwarder: d.forwarder, startBlock: d.blockNumber };
  }
}
fs.writeFileSync(
  path.join(out, "deployments.ts"),
  `// AUTO-GENERATED by scripts/sync.ts — do not edit.\nimport type { Deployment } from "../types";\n\nexport const deployments: Record<number, Deployment> = ${JSON.stringify(deployments, null, 2)};\n`
);
// Agent catalog (catalog/index.json) + per-chain catalogId → agentId maps (contracts/deployments/catalog/*.json).
const catalogFile = path.resolve(__dirname, "..", "..", "catalog", "index.json");
const playbooksFile = path.resolve(__dirname, "..", "..", "catalog", "playbooks.json");
const playbooksData = fs.existsSync(playbooksFile)
  ? (({ agents, generic }) => ({ agents, generic }))(JSON.parse(fs.readFileSync(playbooksFile, "utf8")))
  : { agents: {}, generic: {} };
const domainsFile = path.resolve(__dirname, "..", "..", "catalog", "domains.json");
const domainsData = fs.existsSync(domainsFile) ? JSON.parse(fs.readFileSync(domainsFile, "utf8")).domains : [];
const catalog = fs.existsSync(catalogFile) ? JSON.parse(fs.readFileSync(catalogFile, "utf8")) : [];
const catDir = path.join(depDir, "catalog");
const catalogDeployments: Record<number, Record<string, number>> = {};
if (fs.existsSync(catDir)) {
  for (const f of fs.readdirSync(catDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(fs.readFileSync(path.join(catDir, f), "utf8"));
    catalogDeployments[d.chainId] = d.agents;
  }
}
fs.writeFileSync(
  path.join(out, "catalog.ts"),
  `// AUTO-GENERATED by scripts/sync.ts from catalog/index.json — do not edit.\nimport type { CatalogAgent, Domain, Playbook } from "../types";\n\n` +
    `export const catalog: CatalogAgent[] = ${JSON.stringify(catalog, null, 2)};\n\n` +
    `/** chainId → catalog id → ERC-8004 agentId */\nexport const catalogDeployments: Record<number, Record<string, number>> = ${JSON.stringify(catalogDeployments, null, 2)};\n\n` +
    `/** Ready-to-run tasks per catalog agent + generic ones by skill (catalog/playbooks.json). */\nexport const playbooks: { agents: Record<string, Playbook[]>; generic: Record<string, Playbook[]> } = ${JSON.stringify(playbooksData, null, 2)};\n\n` +
    `/** Domains where AI agents are rented most, with ready-to-create jobs (catalog/domains.json). */\nexport const domains: Domain[] = ${JSON.stringify(domainsData, null, 2)};\n`
);
console.log(`Synced ABIs, ${Object.keys(deployments).length} deployment(s) and ${catalog.length} catalog agents → ${out}`);

// Point the CRE workflow configs at the Monad testnet vault automatically.
const monad = deployments[10143] as { SurelyVault?: string } | undefined;
if (monad?.SurelyVault) {
  const creDir = path.resolve(__dirname, "..", "..", "cre", "surely-judge");
  for (const f of ["config.staging.json", "config.production.json"]) {
    const file = path.join(creDir, f);
    if (!fs.existsSync(file)) continue;
    const cfg = JSON.parse(fs.readFileSync(file, "utf8"));
    cfg.vaultAddress = monad.SurelyVault;
    fs.writeFileSync(file, JSON.stringify(cfg, null, 2) + "\n");
  }
  console.log(`CRE configs → vaultAddress ${monad.SurelyVault}`);
}

